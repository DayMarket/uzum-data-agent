# Команда есть И её можно запустить здесь.
#
# Подключается всеми тремя точками входа: setup.sh, install-windows.sh и
# bin/uzum. Одной копией, а не тремя: правило тут ровно одно, и разъехаться
# оно не должно — иначе мастер и лаунчер разойдутся в том, какой движок они
# считают установленным.
#
# Зачем это вообще. В WSL переменная PATH по умолчанию содержит и
# Windows-часть (interop). npm на Windows кладёт рядом с `codex.cmd` ещё и
# `codex` — обычный sh-скрипт без расширения. На диске Windows каждый файл
# помечен исполняемым, поэтому `command -v codex` находит этот шим и
# отвечает «есть». Запустить его отсюда нельзя: внутри `exec node`, а
# Linux-ноды в WSL нет.
#
# Отказ, ради которого это написано, случился вживую на машине аналитика:
# мастер прошёл до конца, доставил профиль и хуки в /home/<user>/.codex,
# напечатал «Запускай: uzum» — и `uzum --codex` умер с
# `exec: node: not found`. Из этого сообщения не следует ни что движок
# чужой системы, ни что ставить его надо внутрь Ubuntu. Установка при этом
# выглядела полностью успешной, и это тот же класс дефекта, что ловит
# половина проверок в setup.sh: не «упало», а «тихо не работает».
#
# Шаблон — ровно буква диска (/mnt/c/…, /mnt/d/…), а не любой /mnt/*:
# каталог /mnt/data на обычном Linux это нормальное место для программ, и
# отвергать его нельзя. На macOS правило не срабатывает никогда, и это
# правильно: там нет ни WSL, ни диска Windows в PATH.
is_windows_path() {
  case "$1" in
    /mnt/?/*) return 0 ;;
    *) return 1 ;;
  esac
}

have_native() {
  local p
  p="$(command -v "$1" 2>/dev/null)" || return 1
  is_windows_path "$p" && return 1
  return 0
}

# Где нашлась команда, которую have_native отверг. Нужна, чтобы сказать
# человеку правду: не «не установлен», а «установлен не в той системе» —
# иначе он пойдёт ставить второй раз тем же способом и получит то же самое.
foreign_path() { command -v "$1" 2>/dev/null; }

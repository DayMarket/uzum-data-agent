#!/usr/bin/env python3
"""Единственный список путей, где на ноутбуке аналитика обычно лежат
секреты — общий для обоих движков (Codex, Claude Code).

Задача Codex-5, доработка №3 (ревью безопасности): попытка «перевернуть
модель» — запретить чтение по умолчанию и разрешать точечно репозиторий и
системные пути — не удалась (проверено запуском, докстринг у
`tools/render_configs.py::_codex_permission_profile_filesystem_rules`
рассказывает подробно: у Codex `deny` побеждает БЕЗУСЛОВНО, даже более
специфичное правило `read` на подпуть внутри запрещённого дерева его не
отменяет — а поскольку сам репозиторий лежит внутри `$HOME`, широкий deny
на `$HOME/**` вместе с этим не пускает читать и сам репозиторий; `deny`
только на всю файловую систему `/**`  ломает работу инструмента вообще —
даже `echo` падает с SIGABRT, потому что shell не может прочитать
собственные разделяемые библиотеки).

Значит правило 2 («чтение секретов запрещено») в обоих движках — это
СПИСОК ЗАПРЕЩЁННЫХ МЕСТ, а не граница песочницы. Всё, что не попало в этот
список, читается свободно (кроме собственно репозитория и его секретов,
которые оба движка и так знают явно). Это сознательный компромисс, а не
недосмотр — но называть его нужно точно: список расширен до общеизвестных
мест, где разработческие инструменты обычно хранят креды, а не оставлен
двумя путями (секреты этого инструмента + `.env` внутри репозитория), как
было раньше.

Список не претендует на полноту — новый облачный CLI, новый пакетный
менеджер, нестандартное расположение — и такой файл этим списком не
закрыт. Если аналитику нужна реальная граница (а не список), придётся
держать секреты вне `$HOME` целиком или использовать отдельную машину/
контейнер для агента — оба варианта вне рамок этой задачи.

Каждая запись — путь относительно `~`, БЕЗ раскрытия `~` и БЕЗ суффикса
`/**`: раскрытие и суффикс добавляет каждый потребитель сам, в своём
формате (Codex — TOML-glob с `~/`, Claude Code — `Read(~/...)` в
.claude/settings.json). Одни и те же записи здесь читаются в обоих
местах — тест tests/test_codex_permissions.py::
test_claude_code_and_codex_deny_the_same_known_secret_locations сверяет их
и падает, если движки разойдутся.
"""

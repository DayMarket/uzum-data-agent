# lib/hook_scope.py
"""Граница «наша сессия / чужая» — одна на все хуки и на оба движка.

Зачем это вообще есть. Хуки Codex регистрируются в `$CODEX_HOME/hooks.json`,
а этот файл — ОДИН на весь `$CODEX_HOME`, то есть на ВСЕ проекты, которые
аналитик когда-либо откроет в Codex, а не только на наш репозиторий
(в отличие от `.claude/settings.json` у Claude Code, который действует
только в своём проекте). Значит наши скрипты будут запускаться и в чужих
сессиях, и решать «работать или молча выйти» обязаны они сами.

Раньше эту роль пытался играть ОТНОСИТЕЛЬНЫЙ путь в команде хука
(`python3 .claude/hooks/log_event.py`) с расчётом на то, что в чужом проекте
файла по такому пути не окажется и хук «тихо не сработает». Живой запуск это
опроверг (docs/codex-facts.md, раздел 11): отсутствие файла — это не тишина,
а `python3` с ненулевым кодом возврата, и Codex расценивает это как отказ
хука:

    hook: SessionStart Failed
    hook: UserPromptSubmit Blocked

`UserPromptSubmit Blocked` означает, что промпт не доходит до модели вообще —
у аналитика ломается Codex во всех остальных проектах. Поэтому путь в
hooks.json теперь АБСОЛЮТНЫЙ (файл всегда на месте, ненулевого кода нет), а
границу проводит этот модуль.

Признак «сессия идёт внутри нашего клона» — рабочий каталог процесса хука.
Проверено живым запуском на обоих движках (docs/codex-facts.md, раздел 11),
все четыре события, которые мы регистрируем:

  * Codex 0.147.0 — `os.getcwd()` хука == `payload["cwd"]` == рабочий каталог
    сессии (`workdir` в баннере) на SessionStart, UserPromptSubmit,
    PostToolUse, SessionEnd;
  * Claude Code 2.1.220 — то же самое, и вдобавок равно `CLAUDE_PROJECT_DIR`.

Взят именно рабочий каталог процесса, а не `payload["cwd"]`, по трём
причинам: значения совпадают на обоих движках во всех проверенных событиях;
проверку можно сделать ДО чтения stdin, то есть до любой работы; и ровно то
же самое дословно выражается в bash (`pwd -P`) — а
`.claude/hooks/on_session_start.sh` тоже наш хук и тоже должен молчать в
чужом проекте, иначе он сделает `git pull` в чужом репозитории аналитика.

Для Claude Code проверка — безвредный no-op: хуки там регистрируются в
`.claude/settings.json` нашего проекта, поэтому рабочий каталог всегда и есть
наш корень (проверено тем же живым запуском).

«Внутри» — это сам корень или любой каталог под ним: аналитик может запустить
движок из `work/OE-1234`, и это по-прежнему наша сессия.
"""
import os


def repo_root():
    """Корень клона, которому принадлежит ЭТОТ файл.

    Не переменная окружения и не текущий каталог: важно именно то, «чей»
    скрипт сейчас исполняется. В `$CODEX_HOME/hooks.json` прописан абсолютный
    путь к скриптам конкретного клона (того, в котором прогнали `setup.sh`) —
    значит и корень, с которым сравниваем, обязан быть корнем того же клона.

    realpath — потому что сравнивать придётся с realpath рабочего каталога:
    на macOS `/tmp` это симлинк на `/private/tmp`, и без нормализации обеих
    сторон один и тот же каталог не совпал бы сам с собой.
    """
    lib_dir = os.path.dirname(os.path.abspath(__file__))
    return os.path.realpath(os.path.join(lib_dir, os.pardir))


def is_inside(path, root):
    """Лежит ли `path` в `root` (сам корень тоже считается «внутри»).

    Сравнение по компонентам пути, а не голым `startswith`: иначе
    `/x/uzum-data-agent-old` совпал бы с корнем `/x/uzum-data-agent`.
    """
    path = os.path.realpath(path)
    root = os.path.realpath(root)
    return path == root or path.startswith(root.rstrip(os.sep) + os.sep)


def session_is_ours(cwd=None, root=None):
    """True — сессия идёт внутри нашего клона, хук должен работать.
    False — не наша сессия, хук обязан немедленно выйти с кодом 0.

    Никогда не бросает исключений. `os.getcwd()` кидает FileNotFoundError,
    если рабочего каталога больше нет на диске: аналитик сидел в
    `work/OE-1234`, а каталог исчез (переключение ветки, `git clean`,
    `rm -rf` в соседнем окне). Раз эта функция стоит на входе КАЖДОГО хука,
    исключение здесь означало бы ненулевой код возврата, а на
    UserPromptSubmit у Codex — `Blocked`, то есть тот же самый дефект, ради
    которого функция и написана, только через другой вход.

    Каталога нет — значит нельзя утверждать, что сессия наша. Отвечаем
    «не наша»: телеметрия не имеет права мешать работе, а потеря пары строк
    в редчайшем сценарии дешевле заблокированного промпта. Bash-хук в том же
    сценарии ведёт себя так же (см. .claude/hooks/on_session_start.sh).

    Оба аргумента нужны только тестам; в бою вызывается без аргументов.
    """
    try:
        if cwd is None:
            cwd = os.getcwd()
        return is_inside(cwd, root if root is not None else repo_root())
    except OSError:
        return False

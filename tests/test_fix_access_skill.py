"""Тесты скилла fix-access — того, к кому человек идёт, когда что-то не
работает.

Находка живой проверки всех девяти коннекторов: `claude mcp list` показывает
`✔ Connected` в том числе у `openmetadata`, который падает с кодом 1 ещё до
рукопожатия, и у `superset`, который падает на первом же вызове. Это чужой
инструмент, чинить его мы не можем — но скилл не имеет права опираться на
этот признак: диагноз «коннектор подключён, значит дело не в нём» из-за него
уверенно неверный.

Тесты проверяют содержание инструкции. Это слабее, чем проверка поведения, и
здесь это осознанно: скилл — текст для модели, его «поведение» и есть текст.
Поэтому проверяется не наличие слов вообще, а то, что рядом с признаком
подключения стоит запрет на него опираться, и что названа замена — настоящий
вызов инструмента. Такой же приём уже используется в tests/test_skills.py
(проверка порядка шагов в скиллах, работающих с данными).
"""
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILL = REPO_ROOT / ".agents" / "skills" / "fix-access" / "SKILL.md"


def _text():
    return SKILL.read_text(encoding="utf-8")


def test_connection_indicator_is_named_as_not_being_proof():
    """Признак подключения упомянут — и сразу рядом сказано, что он не
    доказательство. Просто «не упоминать mcp list» мало: модель наткнётся на
    него сама, увидит зелёную галочку у девяти коннекторов и успокоится."""
    text = _text()

    assert "claude mcp list" in text, "признак подключения даже не назван"
    assert "Connected" in text

    block = text[text.index("claude mcp list"):]
    block = block[:1200]
    assert "не работают" in block or "не доказ" in block, block[:400]
    assert "openmetadata" in block and "superset" in block, (
        "не названы конкретные коннекторы, на которых признак соврал — без "
        "них это утверждение легко принять за общую осторожность")


def test_skill_forbids_the_diagnosis_based_on_the_indicator():
    text = _text()

    assert re.search(r"[Нн]икогда не пиши.{0,120}подключ", text, re.S), (
        "нет прямого запрета выдавать «коннектор подключён» за диагноз")


def test_skill_names_the_real_check_a_tool_call():
    """Замена признаку: вызвать самый безобидный инструмент на чтение и
    посмотреть на ответ. Без этого запрет оставил бы модель вообще без
    способа проверить."""
    text = _text()

    assert "mcp__<коннектор>__list_" in text, (
        "не сказано, чем проверять по-настоящему")
    assert "вернул ошибку" in text and "ответил" in text, (
        "не сказано, как читать результат проверки")


def test_the_real_check_comes_before_the_list_of_typical_causes():
    """Порядок важен: типовые причины — это догадки по симптому, и разбирать
    их до того, как выяснено, отвечает ли коннектор вообще, значит угадывать
    там, где можно проверить."""
    text = _text()

    check = text.index("Отличи «процесс запущен»")
    causes = text.index("Разбери по типовым причинам")
    assert check < causes, "проверка ответа стоит после списка догадок"


def test_skill_tells_that_a_connector_without_credentials_is_absent_by_design():
    """Вторая находка того же круга: коннектор без кредов теперь не
    включается вовсе. Скилл обязан объяснять это как норму, иначе он будет
    искать поломку там, где её нет."""
    text = _text()

    assert "не включает то, для чего нет доступа" in text, (
        "скилл не знает, что отсутствие коннектора без кредов — это норма")


def test_steps_are_numbered_without_gaps():
    """Скилл переписывался вставкой шага в середину — пропущенный или
    задвоенный номер модель читает как потерянную инструкцию."""
    numbers = [int(m.group(1)) for m in re.finditer(r"^(\d+)\. ", _text(), re.M)]

    assert numbers == list(range(1, len(numbers) + 1)), numbers
